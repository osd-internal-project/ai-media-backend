import {
  IsBoolean,
  IsEmail,
  IsIn,
  IsNotEmpty,
  IsOptional,
  IsString,
  Length,
  ValidateIf,
  ValidateNested,
} from 'class-validator';
import { Type } from 'class-transformer';

export const PAYMENT_METHODS = [
  'CARD',
  'PROMPTPAY',
  'INTERNET_BANKING',
] as const;
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

/** Organization types accepted when creating a new org during checkout. */
export const ORG_TYPES = ['team', 'personal'] as const;
export type OrgType = (typeof ORG_TYPES)[number];

/** Billing profile types. Type-specific fields are validated conditionally. */
export const BILLING_PROFILE_TYPES = ['INDIVIDUAL', 'JURISTIC'] as const;
export type BillingProfileType = (typeof BILLING_PROFILE_TYPES)[number];

/**
 * Billing details supplied inline when buying a package for a brand-new org.
 * Mirrors CreateBillingProfileDto minus userId/organizationId (those are
 * derived from the invoice context: userId from the request, organizationId
 * generated by the server).
 */
export class NewOrgBillingDto {
  @IsIn(BILLING_PROFILE_TYPES)
  type: BillingProfileType;

  @IsString()
  @IsNotEmpty()
  address: string;

  // ── Individual ──────────────────────────────────────────────
  @ValidateIf((o: NewOrgBillingDto) => o.type === 'INDIVIDUAL')
  @IsString()
  @IsNotEmpty()
  fullName?: string;

  @ValidateIf((o: NewOrgBillingDto) => o.type === 'INDIVIDUAL')
  @IsString()
  @Length(13, 13, { message: 'nationalId must be 13 digits' })
  nationalId?: string;

  // ── Juristic ────────────────────────────────────────────────
  @ValidateIf((o: NewOrgBillingDto) => o.type === 'JURISTIC')
  @IsString()
  @IsNotEmpty()
  companyName?: string;

  @ValidateIf((o: NewOrgBillingDto) => o.type === 'JURISTIC')
  @IsString()
  @Length(13, 13, { message: 'taxId must be 13 digits' })
  taxId?: string;

  @ValidateIf((o: NewOrgBillingDto) => o.type === 'JURISTIC')
  @IsString()
  @IsNotEmpty()
  branchCode?: string;

  @ValidateIf((o: NewOrgBillingDto) => o.type === 'JURISTIC')
  @IsString()
  @IsOptional()
  branchName?: string;

  @ValidateIf((o: NewOrgBillingDto) => o.type === 'JURISTIC')
  @IsString()
  @IsNotEmpty()
  contactName?: string;

  @ValidateIf((o: NewOrgBillingDto) => o.type === 'JURISTIC')
  @IsString()
  @IsNotEmpty()
  phone?: string;

  @ValidateIf((o: NewOrgBillingDto) => o.type === 'JURISTIC')
  @IsEmail()
  email?: string;
}

export class CreateInvoiceDto {
  @IsString()
  @IsNotEmpty()
  userId: string;

  @IsIn(PAYMENT_METHODS)
  paymentMethod: PaymentMethod;

  @IsString()
  @IsNotEmpty()
  planPriceId: string;

  /**
   * true  → buy a package for a brand-new organization (created after payment);
   *         orgName + billing are required, organizationId/billingProfileId are ignored.
   * false → buy for an existing org; organizationId + billingProfileId are required.
   */
  @IsBoolean()
  @IsOptional()
  createNewOrganization?: boolean;

  // ── Existing-org purchase ───────────────────────────────────
  @ValidateIf((o: CreateInvoiceDto) => !o.createNewOrganization)
  @IsString()
  @IsNotEmpty()
  organizationId?: string;

  @ValidateIf((o: CreateInvoiceDto) => !o.createNewOrganization)
  @IsString()
  @IsNotEmpty()
  billingProfileId?: string;

  // ── New-org purchase ────────────────────────────────────────
  @ValidateIf((o: CreateInvoiceDto) => o.createNewOrganization === true)
  @IsString()
  @IsNotEmpty()
  orgName?: string;

  @ValidateIf((o: CreateInvoiceDto) => o.createNewOrganization === true)
  @IsIn(ORG_TYPES)
  @IsOptional()
  orgType?: OrgType;

  @ValidateIf((o: CreateInvoiceDto) => o.createNewOrganization === true)
  @IsString()
  @IsOptional()
  orgDescription?: string;

  @ValidateIf((o: CreateInvoiceDto) => o.createNewOrganization === true)
  @ValidateNested()
  @Type(() => NewOrgBillingDto)
  billing?: NewOrgBillingDto;
}
